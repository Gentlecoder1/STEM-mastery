-- Concept-level assessment history; answer keys and submitted answer text stay in Neo4j/API.
create table if not exists public.concept_assessment_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  concept_id text not null,
  score_pct integer not null check (score_pct between 0 and 100),
  passed boolean not null default false,
  question_results jsonb not null default '[]'::jsonb,
  attempted_at timestamptz not null default now()
);

create index if not exists concept_assessment_attempts_user_concept_idx
  on public.concept_assessment_attempts (user_id, concept_id, attempted_at desc);

alter table public.concept_assessment_attempts enable row level security;

drop policy if exists "Concept attempts viewable by owner" on public.concept_assessment_attempts;
create policy "Concept attempts viewable by owner"
  on public.concept_assessment_attempts for select
  using (auth.uid() = user_id);